#!/usr/bin/env node
/**
 * Build the embeddable viewer.
 *
 * The engine is a handful of plain modules with no imports outside each other,
 * so a bundle is a concatenation with the module syntax removed -- the same
 * approach the DSH plugin's `build.mjs` takes, and for the same reason: no
 * bundler is needed for ten files that already have a fixed order.
 *
 * Two artefacts, because two kinds of page:
 *
 *   - `dist/model3d-viewer.mjs` -- an ES module, for a page that can use
 *     `<script type="module">`. Named exports, one instance of the engine per
 *     importing page, and `mount()`/`defineModelViewer()` for the two entry
 *     points.
 *   - `dist/model3d-viewer.js` -- a classic script that defines the
 *     `<model3d-viewer>` element on load, for a page that cannot use modules or
 *     does not want to write JavaScript at all.
 *
 * The module order matters and is not alphabetical: `paint` is a dependency of
 * the parsers, the parsers depend on `gcode`, the viewer depends on `paint`, and
 * the panel depends on everything. Inlining puts every module in one scope, so
 * the order here *is* the dependency graph.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const out = join(root, 'dist');

/** The modules, in dependency order. */
const MODULES = [
  'paint',
  'parsers',
  'gcode',
  'viewer',
  'cube',
  'dom',
  'styles',
  'i18n',
  'loader',
  'persist',
  'picker',
  'bvh',
  'tracer',
  'panel',
  'element',
];

/**
 * Turn one module into plain declarations.
 *
 * Only the forms this project actually uses are handled -- a bare `export
 * function`, `export const`, and the `import { … } from './x.js'` lines that
 * become meaningless once everything shares a scope. A re-export list is dropped
 * for the same reason. Anything more general would be a bundler.
 */
function inline(source) {
  return source
    // Keep the declaration, drop the export keyword.
    .replace(/^export\s+(?=(?:async\s+)?function|const|let|class|var)/gm, '')
    // A local `export { … }` list: the names are already declared above.
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
    // The imports are satisfied by the concatenation order.
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*'[^']*';?\s*$/gm, '');
}

/** The public surface, re-declared as the bundle's exports. */
const EXPORTS = [
  'ViewerPanel',
  'formatSize',
  'mount',
  'defineModelViewer',
  'parseModel',
  'parseStl',
  'parse3mf',
  'parseGcode',
  'createViewer',
  'createCube',
  'createLoader',
  'isModelName',
  'MODEL_EXTENSIONS',
  'injectStyles',
  'createTranslator',
  'pickDictionary',
  'BACKGROUNDS',
  'keyOf',
  'parseSnapshot',
  'serialise',
  'validateSnapshot',
  'createLocalStore',
  'createMemoryStore',
  'debounce',
  'STORE_VERSION',
  'buildBvh',
  'createTracer',
  'renderStillToDataUrl',
  'createStillRender',
  'ModelViewerElement',
  'setLocales',
];

/** The bundled dictionaries, so a page needs no extra requests. */
async function localeLiteral() {
  const entries = [];
  for (const language of ['en', 'ru']) {
    const text = await readFile(join(root, '..', 'locale', `${language}.json`), 'utf8');
    entries.push(`  ${language}: ${JSON.stringify(JSON.parse(text), null, 2).replace(/\n/g, '\n  ')},`);
  }
  return `const LOCALES = {\n${entries.join('\n')}\n};`;
}

const banner = `/**
 * A 3D model viewer: STL, 3MF project files and sliced G-code, on WebGL, per
 * filament, with layers, a build plate and a navigation cube.
 *
 * Generated by \`embed/build.mjs\` -- edit \`embed/src/*.js\` and rebuild. Do not
 * edit this file.
 */`;

const parts = [];
for (const name of MODULES) {
  const source = await readFile(join(root, 'src', `${name}.js`), 'utf8');
  // The entry module declares the export list itself, which the bundle replaces
  // with a real `export { … }` at the end; keeping its own copies would shadow
  // the ones below with identical declarations.
  parts.push(`/* ${'-'.repeat(68)} ${name} */\n${inline(source)}`);
}

const locales = await localeLiteral();

// A page that just includes the script should get the element, without a second
// line of JavaScript. The dictionaries come along so its language attribute
// works out of the box.
const autoDefine = `
// Including this file is the whole install: define the element, with the bundled
// dictionaries, so the tag works in markup and \`language="ru"\` is understood.
setLocales(LOCALES);
defineModelViewer();
`;

const body = parts.join('\n\n');

const esm = `${banner}

${locales}

${body}

${autoDefine}
export { ${EXPORTS.join(', ')} };
`;

const iife = `${banner}
(function () {
'use strict';

${locales}

${body}

${autoDefine}

// One global, for a page that wants to drive the panel from script as well as
// use the element.
globalThis.Model3DViewer = { ${EXPORTS.join(', ')} };
})();
`;

await mkdir(out, { recursive: true });

// The classic script is validated before it is written over a good copy: a
// broken bundle that only fails in a browser is the one failure mode this build
// exists to prevent.
await writeFile(join(out, 'model3d-viewer.mjs'), esm, 'utf8');
await writeFile(join(out, 'model3d-viewer.js'), iife, 'utf8');
await writeFile(join(out, 'locales.json'), JSON.stringify({
  en: JSON.parse(await readFile(join(root, '..', 'locale', 'en.json'), 'utf8')),
  ru: JSON.parse(await readFile(join(root, '..', 'locale', 'ru.json'), 'utf8')),
}, null, 2), 'utf8');

console.log(`dist/model3d-viewer.mjs  ${esm.length} bytes`);
console.log(`dist/model3d-viewer.js   ${iife.length} bytes`);
