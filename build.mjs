#!/usr/bin/env node
/**
 * Build `client.js`, the DSH browser half, from the embeddable viewer.
 *
 * The viewer itself is not a DSH feature any more -- it lives in `embed/` and
 * builds standalone. This file only wraps it: the engine and the panel are
 * inlined exactly as they are into `embed/dist`, and then a small DSH adapter is
 * appended that registers the sidebar tab and hands it a reader.
 *
 * The loader only resolves platform modules (`react`, …), so every source is
 * inlined into the factory body with its module syntax removed. That is also why
 * the embed sources are read here rather than imported: the browser half must be
 * one script with no extra requests.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));

/** Read one source file and turn its ESM exports into plain declarations. */
async function inlineSource(relativePath) {
  const source = await readFile(join(root, relativePath), 'utf8');
  return source
    // Keep the declaration, drop the export keyword.
    .replace(/^export\s+(?=(?:async\s+)?function|const|let|class|var)/gm, '')
    // Drop a trailing `export { ... };` list.
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
    // Inlining puts every module in one scope, so an import statement has nothing
    // left to do; the names it brought in are already declared above.
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*'[^']*';?\s*$/gm, '');
}

/** Read one locale dictionary as an object literal. */
async function inlineLocale(language) {
  const text = await readFile(join(root, `locale/${language}.json`), 'utf8');
  return JSON.parse(text);
}

const LOCALES = ['en', 'ru'];

/**
 * The same order `embed/build.mjs` uses: it is the dependency graph, because
 * inlining makes every module share one scope. A name declared in two places
 * would silently overwrite the first, which is how a cube helper once broke the
 * model's shader compiler.
 */
const MODULES = [
  'paint',
  'parsers',
  'gcode',
  'viewer',
  'cube',
  'dom',
  'styles',
  'i18n',
  'loader',
  'persist',
  'picker',
  'bvh',
  'tracer',
  'panel',
];

const sources = await Promise.all(
  MODULES.map(async (name) => inlineSource(`embed/src/${name}.js`)),
);

const adapter = await inlineSource('src/ui.js');

/** One locale dictionary as an indented object literal for the bundle. */
async function localeLiteral(language) {
  const dictionary = await inlineLocale(language);
  return JSON.stringify(dictionary, null, 2).replace(/\n/g, '\n          ');
}

const bundle = `/**
 * Browser half of the 3D model viewer, for the DSH right sidebar.
 *
 * Generated by \`build.mjs\` from \`embed/src/*.js\` and \`src/ui.js\` — edit those
 * and rebuild; this file is not hand-written.
 *
 * The viewer is the embeddable panel from \`embed/\`, unchanged; the adapter below
 * is the only DSH-specific code. It registers one right-sidebar tab type for
 * \`.stl\`, \`.3mf\` and \`.gcode\` addresses, the body that seats the panel, and the
 * chip title.
 */

window.__ModuleLoader__.load({
  id: 'model3d-viewer',
  factory(require) {
    const React = require('react');

${sources.map((source, index) => `/* ${'-'.repeat(64)} ${MODULES[index]} */\n\n${source}`).join('\n\n')}

/* ---------------------------------------------------------------- adapter -- */

${adapter}

/* ----------------------------------------------------------------- plugin -- */

    const NAMESPACE = 'model3dViewer';
    const KIND = 'model3d';
    const ID = 'model3d-viewer';
    const EXTENSIONS = /\\.(stl|3mf|gcode)$/i;

    const { ModelViewer, ModelTitle } = createModelUI(React);

    /** Whether this tab type claims the address: a session file with a model suffix. */
    function canOpen(address) {
      const file = parseFileAddress(address);
      return file !== undefined && EXTENSIONS.test(file.path);
    }

    /** The guide entry's title: the file's basename. */
    function basenameOf(address) {
      const file = parseFileAddress(address);
      if (file === undefined) return address;
      return file.path.split('/').pop() ?? address;
    }

    return {
      inject: ['slots', 'locale', 'sidebarRightTabs', 'remote', 'remote.workspaceFiles'],

      apply(ctx) {
        const t = ctx.locale.bind(NAMESPACE);

        const dictionaries = {
${(await Promise.all(LOCALES.map(async (language) => `          ${language}: ${await localeLiteral(language)},`))).join('\n')}
        };

        ctx.effect(() => ctx.locale.register(NAMESPACE, dictionaries), 'model3d-viewer: dictionaries');

        ctx.effect(() => ctx.sidebarRightTabs.register({
          id: ID,
          kind: KIND,
          multiple: true,
          priority: 'extension',
          patterns: ['dsh-resource://file/**'],
          canOpen,
          title: basenameOf,
        }), 'model3d-viewer: type');

        // One read per tab occurrence; the panel aborts it when the tab unmounts.
        // A 3MF that carries a sliced plate is read once and yields both views.
        const readModel = async (file, signal) => {
          const result = await ctx.remote.workspaceFiles.readBytes(file.sessionId, file.path, {}, signal);
          if (!result.ok) throw new Error((result.error && result.error.message) || 'The file could not be read');
          const bytes = new Uint8Array(result.value.data);
          const parsed = parseModel(file.path, bytes);
          if (parsed.sliced !== undefined) return parsed;
          return { mesh: parsed };
        };

        // The panel picks its text from these dictionaries through its own
        // translator, so both languages ship in one bundle and neither needs a
        // second request.
        ctx.effect(() => ctx.slots.inject('sidebar.right.pane.tab', () => ctx.slots.register({
          name: 'sidebar.right.pane.tab',
          key: ID,
          locale: NAMESPACE,
          inject: () => ({ readModel, locales: dictionaries }),
        }, ModelViewer)), 'model3d-viewer: body');

        ctx.effect(() => ctx.slots.inject('sidebar.right.pane.tab.title', () => ctx.slots.register({
          name: 'sidebar.right.pane.tab.title',
          key: ID,
          locale: NAMESPACE,
        }, ModelTitle)), 'model3d-viewer: title');
      },
    };
  },
});
`;

await writeFile(join(root, 'client.js'), bundle, 'utf8');
console.log(`client.js written (${bundle.length} bytes)`);
